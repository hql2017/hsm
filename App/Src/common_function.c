 void delay_us(volatile unsigned int nus)
{   
    volatile unsigned int start=DWT->CYCCNT,tcnt = 0;        //刚进入时的计数器值   
    volatile unsigned int ticks=nus*(SystemCoreClock/1000000);//nus需要的节拍数 
    while(tcnt<ticks)
    {
        tcnt=  DWT->CYCCNT- start;
    }                                   
}
