unsigned short CRC16_TABLE_Check(unsigned char *str, unsigned short len)
{ 
	unsigned short index,crch,crcl;
	unsigned short i;
	unsigned short crc;

	crch = 0xFF; 
	crcl = 0xFF; 

	for(i = 0; i < len; i++)
	{ 
	index = crch^str[i];  
	crch  = crcl^CRCTABH[index]; 
	crcl  = CRCTABL[index];     
	} 
	crc = crch<<8 | crcl; 
	return crc; 
} 